import { Workbook } from 'exceljs';

export type ImportKind = 'products' | 'customers';
export interface ImportRow { row: number; name: string; data: any; state: 'ready' | 'duplicate' | 'invalid' | 'saved' | 'queued' | 'failed'; message: string; }
const fields = {
  products: ['Name', 'Barcode', 'Category', 'Uom', 'Price', 'Rate', 'Cost', 'Lowest Price', 'Stock', 'Include Tax', 'Description'],
  customers: ['Name', 'Phone', 'Email', 'Address', 'Customer Category', 'Term', 'Discount Percent', 'Enable Discount', 'Require Digit Sign', 'Description']
};
const key = (value: string) => value.trim().replace(/[\s_*]/g, '').toLowerCase();
const normalized = (value: any) => String(value ?? '').trim().toLowerCase();

export function buildMasterTemplate(kind: ImportKind): Workbook {
  const workbook = new Workbook();
  const sheet = workbook.addWorksheet(kind === 'products' ? 'Products' : 'Customers');
  sheet.addRow(fields[kind]);
  sheet.getRow(1).height = 30;
  sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF17365D' } };
  fields[kind].forEach((name, i) => {
    sheet.getColumn(i + 1).width = name === 'Address' || name === 'Description' ? 42 : 24;
    if (['Name', 'Barcode', 'Phone', 'Email'].includes(name)) sheet.getColumn(i + 1).numFmt = '@';
  });
  sheet.views = [{ state: 'frozen', ySplit: 1 }];
  const instructions = workbook.addWorksheet('Instructions');
  instructions.getColumn(1).width = 115;
  [kind === 'products' ? 'Products: Name and Price are required. Barcode must be text (preserve leading zeros).' : 'Customers: Name is required. Phone must be text (preserve leading zeros).',
    'Enter data starting in row 2 of the first sheet. Delete any unused rows. Maximum 2000 rows per file.',
    'New records only. Existing matching records are skipped. Existing records are never overwritten.',
    'Product Code and Customer Code are generated by the system. Optional Code / Customer Code columns may identify existing records to skip.',
    'Booleans: Yes/No, True/False, or 1/0. No formulas. Blank optional numbers default to zero; Rate defaults to 1.',
    'Customer Term: Cash Sale, On Credit, or Net 30 Days. Discount Percent: 0 to 100.',
    'Review the preview before confirming. Offline imports are saved on this device and queued for API sync.'
  ].forEach(text => instructions.addRow([text]));
  return workbook;
}

/** Export the same editable columns accepted by the importer, plus existing codes. */
export function buildMasterExport(kind: ImportKind, records: any[]): Workbook {
  const workbook = buildMasterTemplate(kind);
  const sheet = workbook.worksheets[0];
  const headers = [...fields[kind], kind === 'products' ? 'Code' : 'Customer Code'];
  const property = kind === 'products'
    ? ['name', 'barcode', 'category', 'uom', 'price', 'rate', 'cost', 'lowestPrice', 'stock', 'includeTax', 'description', 'code']
    : ['name', 'phone', 'email', 'address', 'customerCategory', 'term', 'discountPercent', 'enableDiscount', 'requireDigitSign', 'description', 'customerCode'];
  const numeric = kind === 'products' ? [4, 5, 6, 7, 8] : [6];
  const boolean = kind === 'products' ? [9] : [7, 8];
  const rows = records.map(record => property.map((field, index) => {
    const value = record[field] ?? '';
    if (numeric.includes(index)) return Number(value === '' ? (field === 'rate' ? 1 : 0) : value);
    if (boolean.includes(index)) return (value === '' ? field === 'enableDiscount' : !!value) ? 'Yes' : 'No';
    return String(value);
  }));
  sheet.addTable({ name: kind === 'products' ? 'ProductData' : 'CustomerData', ref: 'A1', headerRow: true,
    style: { theme: 'TableStyleMedium2', showRowStripes: true }, columns: headers.map(name => ({ name, filterButton: true })), rows });
  sheet.getColumn(headers.length).width = 24;
  sheet.getColumn(headers.length).numFmt = '@';
  numeric.forEach(index => sheet.getColumn(index + 1).numFmt = kind === 'products' && index === 8 ? '0' : '0.00');
  for (let row = 2; row <= sheet.rowCount; row++) {
    sheet.getRow(row).height = 26;
    sheet.getRow(row).alignment = { vertical: 'middle' };
  }
  return workbook;
}

export function isExistingMaster(kind: ImportKind, data: any, existing: any[]): boolean {
  return existing.some(record => {
    if (kind === 'products') {
      return !!data.code && normalized(record.code) === normalized(data.code) ||
        !!data.barcode && normalized(record.barcode) === normalized(data.barcode) ||
        !data.barcode && normalized(record.name) === normalized(data.name);
    }
    return !!data.customerCode && normalized(record.customerCode) === normalized(data.customerCode) ||
      normalized(record.name) === normalized(data.name) && normalized(record.phone) === normalized(data.phone);
  });
}

export async function readMasterExcel(buffer: ArrayBuffer, kind: ImportKind, existing: any[]): Promise<ImportRow[]> {
  const workbook = new Workbook();
  await workbook.xlsx.load(buffer);
  const sheet = workbook.worksheets.find(s => normalized(s.name) === kind) || workbook.worksheets[0];
  if (!sheet) throw new Error('The workbook has no worksheet.');
  if (sheet.rowCount > 2001) throw new Error('Maximum 2000 data rows per file. Remove unused rows and try again.');
  const columns = new Map<string, number>();
  sheet.getRow(1).eachCell((cell, column) => {
    const name = key(cell.text);
    if (columns.has(name)) throw new Error('Duplicate column: ' + cell.text);
    columns.set(name, column);
  });
  const requiredHeaders = kind === 'products' ? ['Name', 'Price'] : ['Name', 'Phone'];
  for (const header of requiredHeaders) if (!columns.has(key(header))) throw new Error('Missing column: ' + header + '. Use the ' + kind + ' template.');
  const rows: ImportRow[] = [];
  const known = [...existing];
  for (let rowNumber = 2; rowNumber <= sheet.rowCount; rowNumber++) {
    const row = sheet.getRow(rowNumber);
    if (!row.hasValues) continue;
    const errors: string[] = [];
    const text = (header: string, strictText = false) => {
      const column = columns.get(key(header));
      if (!column) return '';
      const cell = row.getCell(column);
      if (cell.value == null) return '';
      if (cell.type === 6 || typeof cell.value === 'object' && ('formula' in cell.value || 'sharedFormula' in cell.value)) {
        errors.push(header + ': formulas are not allowed'); return '';
      }
      if (strictText && typeof cell.value === 'number') errors.push(header + ': format the cell as Text to preserve leading zeros');
      return cell.text.trim();
    };
    const number = (header: string, fallback = 0, required = false, max = 999999, min = 0) => {
      const raw = text(header);
      if (!raw) { if (required) errors.push(header + ' is required'); return fallback; }
      const value = Number(raw);
      if (!Number.isFinite(value) || value < min || value > max) { errors.push(header + ': invalid number'); return fallback; }
      return value;
    };
    const flag = (header: string, fallback = false) => {
      const raw = normalized(text(header));
      if (!raw) return fallback;
      if (['yes', 'true', '1'].includes(raw)) return true;
      if (['no', 'false', '0'].includes(raw)) return false;
      errors.push(header + ': use Yes or No'); return fallback;
    };
    const name = text('Name');
    if (!name) errors.push('Name is required');
    let data: any;
    if (kind === 'products') {
      data = { name, code: text('Code', true), barcode: text('Barcode', true), category: text('Category') || 'DEFAULT',
        uom: text('Uom') || 'UNIT', price: number('Price', 0, true), rate: number('Rate', 1), cost: number('Cost'),
        lowestPrice: number('Lowest Price'), stock: number('Stock', 0, false, 2147483647, -2147483648), includeTax: flag('Include Tax'), description: text('Description') };
      if (!Number.isInteger(data.stock)) errors.push('Stock must be a whole number');
    } else {
      data = { name, customerCode: text('Customer Code', true), phone: text('Phone', true), email: text('Email'), address: text('Address'),
        customerCategory: text('Customer Category') || 'DEFAULT', term: text('Term') || 'Cash Sale', discountPercent: number('Discount Percent', 0, false, 100),
        enableDiscount: flag('Enable Discount', true), requireDigitSign: flag('Require Digit Sign'), description: text('Description'), branches: [] };
      if (!['Cash Sale', 'CASH SALE', 'Cash', 'On Credit', 'Net 30 Days'].includes(data.term)) errors.push('Term must be Cash Sale, On Credit or Net 30 Days');
      if (data.email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(data.email)) errors.push('Email is invalid');
    }
    const duplicate = isExistingMaster(kind, data, known);
    rows.push({ row: rowNumber, name, data, state: errors.length ? 'invalid' : duplicate ? 'duplicate' : 'ready',
      message: errors.join('; ') || (duplicate ? 'Already exists — skipped' : 'Ready to import') });
    if (!errors.length && !duplicate) known.push(data);
  }
  if (!rows.length) throw new Error('No data rows found. Enter data below the header row.');
  return rows;
}
